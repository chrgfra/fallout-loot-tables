<h2>Serums</h2>
<p>Serums are a special kind of chem that can apply a specific mutation. Serums are extremely rare (Rarity 6) and the knowledge of their creation is a closely guarded secret.</p>
<p>In addition to causing a mutation, serums suppress the negative penalties of <em>all</em> mutations a character has until the end of the current scene.</p>
<p>Like with other chems, the duration is impacted by the Chemist Perk or BioCommMesh armor.</p>