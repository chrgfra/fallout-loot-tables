<h1>Mutations</h1>
<p>Adding rules for mutations from Fallout 76. Mutations are like added Traits.</p>

<p>Mutations may occur when a character takes radiation damage. When you take rad damage, roll a number of CD equal to the number of times you were exposed to radiation damage this session. If you roll 2 or more Effects, you gain a mutation. Roll on the mutation table.</p>

<p>If a character with a mutation takes RadAway or similar chems, they have a chance to lose the mutation. Whenever you take RadAway, roll a number of CD equal to the number of doses you have taken this session. If you roll 1 or more Effects, you lose a mutation. The mutation lost is determined by the GM.</p>

