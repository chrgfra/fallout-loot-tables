<p>SPECIAL stats modified by mutations do not count for the purposes of Perk requirements, but count for derived stats. Regardless of a stat's rating, the TN for skill tests cannot exceed 16. Bonuses and penalties to INT do not affect the character's initial ranks in Skills.</p>

<h2>Mutation Perks</h2>
<p>These Perks have a direct impact on Mutations.</p>

<h3>Strange in Numbers</h3>
<div>
  <strong>Ranks:</strong> 1<br />
  <strong>Requirements:</strong> CHA 6, Level 5+
</div>
<p>Your mutations are more effective when you are around other mutants.</p>

<h3>Class Freak</h3>
<div>
  <strong>Ranks:</strong> 3
  <strong>Requirements:</strong> LCK 7, Level 8+
</div>
<p></p>
<p>Each time you take this perk, the level requirement increases by +5.</p>

<h3>Starched Genes</h3>
<div>
  <strong>Ranks:</strong> 2<br />
  <strong>Requirements:</strong> LCK 6, Level 10+
</div>
<p>Your chances of randomly gaining (and losing) a mutation are halved.</p>
<p>You will no longer randomly gain (or lose) mutations.</p>
<p>Each time you take this perk, the level requirement increases by +10.</p>

<h3>Super Mutated</h3>
<div>
  <strong>Ranks:</strong> 1<br />
  <strong>Requirements:</strong> END 8, not a robot, immune to Radiation.
</div>
<p>You are able to gain mutations, despite being immune to radiation.</p>

